"""Write api/_lib/registry/seed.js: the bundled example packages (packages/<name>/)
as approved TB Package Index packages owned by the "tb" system owner, plus the
standard library names the index reserves.

    uv run python scripts/gen_registry_seed.py          # rewrite seed.js
    uv run python scripts/gen_registry_seed.py --check  # exit 1 if it's stale

Run it after changing anything in packages/ or adding a library;
tests/test_registry_site.py fails while seed.js is out of date.

The archives are built by package_zip(), which scripts/build_site.py also uses
for the static packages/<name>.zip downloads, so both are byte-identical: stored
(not compressed), sorted, fixed timestamps and attributes, one top folder <name>/.
Standard library only.
"""

from __future__ import annotations

import base64
import hashlib
import io
import json
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGES = ROOT / "packages"
SEED_JS = ROOT / "api" / "_lib" / "registry" / "seed.js"
ZIP_DATE = (2026, 10, 26, 0, 0, 0)
SEED_CREATED = "2026-10-26T00:00:00.000Z"
PACKAGE_SKIP = {".DS_Store", "tb.lock"}


def package_files(folder: Path) -> list[Path]:
    files = []
    for path in sorted(folder.rglob("*")):
        parts = path.relative_to(folder).parts
        if (not path.is_file() or path.name in PACKAGE_SKIP or "__pycache__" in parts
                or "tb_packages" in parts or any(p.startswith(".") for p in parts)):
            continue
        files.append(path)
    return files


def package_zip(folder: Path) -> bytes:
    """A reproducible zip of a package folder, every file under <name>/."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_STORED) as zf:
        for path in package_files(folder):
            rel = "/".join(path.relative_to(folder).parts)
            info = zipfile.ZipInfo(f"{folder.name}/{rel}", ZIP_DATE)
            info.compress_type = zipfile.ZIP_STORED
            info.create_system = 3  # the same bytes on every OS
            info.external_attr = (0o100644 << 16)
            zf.writestr(info, path.read_bytes())
    return buffer.getvalue()


def example_packages() -> list[Path]:
    if not PACKAGES.is_dir():
        return []
    return [p for p in sorted(PACKAGES.iterdir()) if p.is_dir() and (p / "tb.toml").is_file()]


def seed_entries() -> list[dict]:
    sys.path.insert(0, str(ROOT))
    from tbtools import pkg

    entries = []
    for folder in example_packages():
        meta = pkg.read_manifest(str(folder))
        package = meta["package"]
        data = package_zip(folder)
        readme = folder / "README.md"
        entries.append({
            "name": folder.name,
            "version": str(package["version"]),
            "description": package.get("description", ""),
            "license": package.get("license", ""),
            "keywords": list(package.get("keywords", [])),
            "dependencies": meta.get("dependencies", {}),
            "entry": pkg.package_entry(str(folder), folder.name),
            "files": sorted("/".join(p.relative_to(folder).parts) for p in package_files(folder)),
            "readme": readme.read_text(encoding="utf-8") if readme.is_file() else "",
            "sha256": hashlib.sha256(data).hexdigest(),
            "size": len(data),
            "created": SEED_CREATED,
            "zip": base64.b64encode(data).decode("ascii"),
        })
    return entries


def render() -> str:
    sys.path.insert(0, str(ROOT))
    import tb

    lines = [
        "// Generated by scripts/gen_registry_seed.py; don't edit by hand.",
        "// The bundled example packages (approved, owned by the \"tb\" system owner)",
        "// and the standard library names no package may use.",
        "",
        f"export const STDLIB_NAMES = {json.dumps(sorted(tb.list_libraries()))};",
        "",
        'export const SEED_OWNER = "tb";',
        "",
        "export const SEED_PACKAGES = " + json.dumps(seed_entries(), indent=1, ensure_ascii=True) + ";",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    text = render()
    current = SEED_JS.read_text(encoding="utf-8") if SEED_JS.exists() else ""
    if "--check" in args:
        if current != text:
            print("api/_lib/registry/seed.js is out of date: run uv run python scripts/gen_registry_seed.py", file=sys.stderr)
            import difflib
            diff = difflib.unified_diff(current.splitlines(), text.splitlines(), "seed.js", "expected", lineterm="", n=0)
            print("\n".join(line[:200] for line in list(diff)[:12]), file=sys.stderr)
            return 1
        print("seed.js is up to date")
        return 0
    if current != text:
        SEED_JS.parent.mkdir(parents=True, exist_ok=True)
        SEED_JS.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {SEED_JS.relative_to(ROOT)}")
    else:
        print("seed.js already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
