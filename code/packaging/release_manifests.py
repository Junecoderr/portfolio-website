"""Write the package-manager files for a release from the built assets.

Usage (from code/, after every asset is in dist/; the release job runs it):

    python packaging/release_manifests.py                    # all of them
    python packaging/release_manifests.py --only apt         # just the apt index
    python packaging/release_manifests.py --dist dist --out dist/manifests

Writes, from the files' real sha256 sums:

  dist/manifests/homebrew/tb.rb
      A Homebrew formula (macOS arm64 + Intel, Linux x64 + arm64). It goes in
      a tap repository (github.com/<owner>/homebrew-tb, Formula/tb.rb);
      then `brew install <owner>/tb/tb`.
  dist/manifests/winget/manifests/t/TBLang/TB/<version>/
      The three winget manifests (version, installer, en-US locale) for a pull
      request to microsoft/winget-pkgs; then `winget install TBLang.TB`.
  dist/Packages, dist/Packages.gz, dist/Release
      A flat apt repository index for every tb_<version>_<arch>.deb in dist/.
      The release job signs Release (InRelease, Release.gpg) when the
      APT_GPG_PRIVATE_KEY secret exists and publishes them as release assets;
      code.tanisha.ceo/apt/<file> serves them (vercel.json), so
      `deb [signed-by=/usr/share/keyrings/tb.gpg] https://code.tanisha.ceo apt/`
      (the "apt/" form, not "./": apt would request /apt/./InRelease).

Download URLs are versioned (code.tanisha.ceo/dl/<version>/<file>), so a
manifest keeps working after the next release.
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import io
import re
import sys
import tarfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "packaging"))
import build  # noqa: E402

SITE = "https://code.tanisha.ceo"
WINGET_ID = "TBLang.TB"
WINGET_SCHEMA = "1.10.0"
SUMMARY = "A small, friendly programming language"
ISS = ROOT / "packaging" / "windows" / "tb.iss"
# Homebrew: (on_os, on_arch) -> asset.
BREW_ASSETS = {
    ("macos", "arm"): "tb-macos-arm64.zip",
    ("macos", "intel"): "tb-macos-x64.zip",
    ("linux", "arm"): "tb-linux-arm64.tar.gz",
    ("linux", "intel"): "tb-linux-x64.tar.gz",
}
WINDOWS_SETUP = "tb-windows-x64-setup.exe"
APT_DIR = "apt"  # the flat repository's folder: code.tanisha.ceo/apt/


def url(version: str, name: str) -> str:
    return f"{SITE}/dl/{version}/{name}"


def sha256_of(dist: Path, name: str) -> str:
    path = dist / name
    if not path.is_file():
        raise SystemExit(f"release_manifests: {path} is missing")
    return build.sha256(path)


def homebrew_formula(version: str, sums: dict[str, str]) -> str:
    blocks = []
    for os_name in ("macos", "linux"):
        inner = []
        for arch in ("arm", "intel"):
            name = BREW_ASSETS[(os_name, arch)]
            inner.append(f'    on_{arch} do\n      url "{url(version, name)}"\n      sha256 "{sums[name]}"\n    end')
        blocks.append(f"  on_{os_name} do\n" + "\n".join(inner) + "\n  end")
    return f'''# Generated by packaging/release_manifests.py for TB {version}. Do not edit.
class Tb < Formula
  desc "Small, friendly programming language"
  homepage "{SITE}"
  version "{version}"
  license "MIT"

{chr(10).join(blocks)}

  def install
    # The folder is a frozen app: tb only works next to _internal/.
    libexec.install Dir["*"]
    bin.install_symlink libexec/"tb"
  end

  test do
    assert_equal "TB #{{version}}", shell_output("#{{bin}}/tb --version").strip
    (testpath/"hello.tb").write "say(6 * 7)\\n"
    assert_equal "42", shell_output("#{{bin}}/tb #{{testpath}}/hello.tb").strip
  end
end
'''


def inno_app_id() -> str:
    m = re.search(r"^AppId=\{(\{[0-9A-F-]+\})", ISS.read_text(encoding="utf-8"), re.M)
    if not m:
        raise SystemExit("release_manifests: no AppId in tb.iss")
    return m.group(1)


def winget_manifests(version: str, setup_sha: str) -> dict[str, str]:
    head = f"# yaml-language-server: $schema=https://aka.ms/winget-manifest.{{}}.{WINGET_SCHEMA}.schema.json\n"
    common = f"PackageIdentifier: {WINGET_ID}\nPackageVersion: {version}\n"
    tail = f"ManifestVersion: {WINGET_SCHEMA}\n"
    return {
        f"{WINGET_ID}.yaml": head.format("version") + common
        + "DefaultLocale: en-US\nManifestType: version\n" + tail,
        f"{WINGET_ID}.installer.yaml": head.format("installer") + common
        + "InstallerType: inno\nScope: user\nUpgradeBehavior: install\n"
        + f"ProductCode: '{inno_app_id()}_is1'\n"
        + "Commands:\n- tb\nFileExtensions:\n- tb\n"
        + "Installers:\n- Architecture: x64\n"
        + f"  InstallerUrl: {url(version, WINDOWS_SETUP)}\n"
        + f"  InstallerSha256: {setup_sha.upper()}\n"
        + "ManifestType: installer\n" + tail,
        f"{WINGET_ID}.locale.en-US.yaml": head.format("defaultLocale") + common
        + "PackageLocale: en-US\nPublisher: TB\n"
        + f"PublisherUrl: {SITE}\nPackageName: TB\nPackageUrl: {SITE}\n"
        + "License: MIT\nMoniker: tb\n"
        + f"ShortDescription: {SUMMARY}\n"
        + f"ReleaseNotesUrl: {SITE}/releases\n"
        + "Tags:\n- programming-language\n- security\n- education\n"
        + "ManifestType: defaultLocale\n" + tail,
    }


def deb_control(path: Path) -> str:
    """The control file inside a .deb (an ar archive holding control.tar.*)."""
    data = path.read_bytes()
    if not data.startswith(b"!<arch>\n"):
        raise SystemExit(f"release_manifests: {path.name} is not a .deb")
    pos = 8
    while pos + 60 <= len(data):
        header = data[pos:pos + 60]
        name = header[:16].decode("ascii").strip().rstrip("/")
        size = int(header[48:58].decode("ascii").strip())
        body = data[pos + 60:pos + 60 + size]
        if name.startswith("control.tar"):
            with tarfile.open(fileobj=io.BytesIO(body), mode="r:*") as tf:
                names = tf.getnames()
                member = "./control" if "./control" in names else "control"
                return tf.extractfile(member).read().decode("utf-8")
        pos += 60 + size + (size % 2)
    raise SystemExit(f"release_manifests: {path.name} has no control.tar")


def apt_packages(dist: Path, debs: list[Path]) -> str:
    entries = []
    for deb in debs:
        blob = deb.read_bytes()
        entry = deb_control(deb).rstrip("\n") + "\n"
        entry += f"Filename: {APT_DIR}/{deb.name}\nSize: {len(blob)}\n"
        entry += f"MD5sum: {hashlib.md5(blob).hexdigest()}\n"
        entry += f"SHA256: {hashlib.sha256(blob).hexdigest()}\n"
        entries.append(entry)
    return "\n".join(entries)


def apt_release(files: dict[str, bytes], archs: list[str], now: float | None = None) -> str:
    date = time.strftime("%a, %d %b %Y %H:%M:%S UTC", time.gmtime(now))
    # Suite/Codename match the "apt/" in the sources line, or apt warns.
    lines = ["Origin: TB", "Label: TB", f"Suite: {APT_DIR}", f"Codename: {APT_DIR}", f"Date: {date}",
             f"Architectures: {' '.join(archs)}", "SHA256:"]
    for name, blob in files.items():
        lines.append(f" {hashlib.sha256(blob).hexdigest()} {len(blob)} {name}")
    return "\n".join(lines) + "\n"


def write_apt(dist: Path, version: str) -> list[Path]:
    debs = sorted(dist.glob(f"tb_{version}_*.deb"))
    if not debs:
        raise SystemExit(f"release_manifests: no tb_{version}_*.deb in {dist}")
    packages = apt_packages(dist, debs).encode("utf-8")
    packed = gzip.compress(packages, mtime=0)
    archs = sorted(re.search(r"^Architecture: (\S+)", deb_control(d), re.M).group(1) for d in debs)
    release = apt_release({"Packages": packages, "Packages.gz": packed}, archs)
    out = [dist / "Packages", dist / "Packages.gz", dist / "Release"]
    out[0].write_bytes(packages)
    out[1].write_bytes(packed)
    out[2].write_text(release, encoding="utf-8", newline="\n")
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dist", default=str(ROOT / "dist"))
    parser.add_argument("--out", default=None, help="default: <dist>/manifests")
    parser.add_argument("--only", choices=["homebrew", "winget", "apt"], action="append")
    args = parser.parse_args()
    dist = Path(args.dist).resolve()
    out = Path(args.out).resolve() if args.out else dist / "manifests"
    only = set(args.only or ["homebrew", "winget", "apt"])
    version = build.VERSION
    written: list[Path] = []
    if "homebrew" in only:
        sums = {name: sha256_of(dist, name) for name in BREW_ASSETS.values()}
        path = out / "homebrew" / "tb.rb"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(homebrew_formula(version, sums), encoding="utf-8", newline="\n")
        written.append(path)
    if "winget" in only:
        folder = out / "winget" / "manifests" / WINGET_ID[0].lower() / Path(*WINGET_ID.split(".")) / version
        folder.mkdir(parents=True, exist_ok=True)
        for name, text in winget_manifests(version, sha256_of(dist, WINDOWS_SETUP)).items():
            (folder / name).write_text(text, encoding="utf-8", newline="\n")
            written.append(folder / name)
    if "apt" in only:
        written += write_apt(dist, version)
    for path in written:
        print(f"[manifests] wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
